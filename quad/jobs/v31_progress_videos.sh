#!/bin/bash
# v31 の seed 1・2・3 の学習の経過の動画（同じ 8 つの時点・同じ指令。区切りの画面に 3 seed の表）
# 説明の {fwd#1} などは khr_quad_progress.py の Stats.fill が測定の数字に置き換える
cd "$(dirname "$0")/../.."   # リポジトリのルート
source ../bin/activate
SCHED="0.3,0,0:3;push:0,-1.0;0.3,0,0:2;0,0,0.5:2.5;0,0.15,0:2.5;-0.3,0,0:2.5"
COMMON=(--schedule "$SCHED" --card_s 5 --stats_prefix experiments/quad_progress/v31
        --intro_image experiments/quad_progress/v31_progress.png --intro_s 10 --outro_s 12)
S0="まだ何も学んでいない。最初の姿勢のまま立っているだけで、指令に反応しない/学習中は行動に乱数を足して試すので転ぶが、動画は乱数なしで動かしている（以下同じ）"
INTRO_BODY=("どの時点も同じ指令: 前進 3 秒 → 横から押す → 前進 2 秒 → 左旋回 → 左へ → 後退（各 2.5 秒）"
            "図は 3 seed の測定（行動の乱数・個体差なし）。①〜⑧ が動画の時点"
            "区切りの画面の表も 3 seed の測定。この動画の seed の行を明るくしている")

rec1() {
DISPLAY=:1 OMP_NUM_THREADS=4 python quad/khr_quad_progress.py record -e khr-quadruped31-s1 "${COMMON[@]}" \
  --intro "KHR-3HV 四足歩行 v31 の学習の経過（seed 1）" "全 4000 回の学習のうち 8 つの時点" "${INTRO_BODY[@]}" \
  --stage 0 "学習の前" "$S0" \
  --stage 100 "足を動かし始める" "足を小さく動かすが、まだどの指令にも進めない（左旋回 {turn#1}）/この seed がその場で回れるようになるのは 200 回目（{turn#1@200}）" \
  --stage 300 "動作が出来始める" "3 seed でいちばん早く前後に歩き出す（前進 {fwd#1}・後退 {back#1}）/ほかの 2 seed の前進はまだ {fwd#2}・{fwd#3}" \
  --stage 400 "前後に歩けるようになる" "前進 {fwd#1}・後退 {back#1}。横歩きはまだ（{left#1}）/押しには 3 seed でいちばん弱い時期（全強度の押しで {push#1}。seed 2 は {push#2}）" \
  --stage 1000 "中盤: 前後の速さはほぼ完成" "前進 {fwd#1}・後退 {back#1}で、最後とほぼ同じ。横歩きは {left#1}/押しにはまだ弱い（{push#1}。seed 2・3 は {push#2}・{push#3}）" \
  --stage 2000 "中盤の終わり: 押されても転ばなくなる" "押されて転ぶ回数: 1300 回目 {push#1@1300} → 2000 回目 {push#1}（2300 回目で 0）/学習の押しの強さが最大になる 2080 回目とほぼ同じ時期" \
  --stage 3000 "終盤: 脚を大きく振り始める" "前進のときの膝の振れ幅: 2000 回目 {knee#1@2000} → 3000 回目 {knee#1}（2900 回目から増える）/後脚の足上げ: {clear_r#1@2000} → {clear_r#1}" \
  --stage 3999 "完成" "前進 {fwd#1}・後退 {back#1}・左へ {left#1}・左旋回 {turn#1}/膝の振れ幅 {knee#1}、後脚の足上げ {clear_r#1}、押されて転ぶ回数 {push#1}" \
  --outro "seed 1 のまとめ" \
    "200 回目: その場で回れる（seed 2 より 100 回遅く、seed 3 より 100 回早い）" \
    "300 回目: 3 seed でいちばん早く前後に歩き出す" \
    "200〜1300 回目: 押しには 3 seed でいちばん弱い（全強度の押しで 22〜38 回。seed 2 は 2〜10 回）" \
    "2000〜2300 回目: 押されても転ばなくなる" \
    "2900 回目から: 膝を大きく振る。前進はたいてい 3 seed でいちばん速い（37 時点のうち 25）" \
  -o media/videos/quad_progress/v31-s1_progress.mp4 2>&1 | grep "^\[record\]\|Error"
}

rec2() {
DISPLAY=:1 OMP_NUM_THREADS=4 python quad/khr_quad_progress.py record -e khr-quadruped31-s2 "${COMMON[@]}" \
  --intro "KHR-3HV 四足歩行 v31 の学習の経過（seed 2）" "10/13 に実機で歩かせた方策。全 4000 回の学習のうち 8 つの時点" "${INTRO_BODY[@]}" \
  --stage 0 "学習の前" "$S0" \
  --stage 100 "足を動かし始め、その場で回れるようになる" "3 seed でいちばん早く、その場で回れる（左旋回 {turn#2}）/前後・横にはまだ進めない" \
  --stage 300 "動作が出来始める" "足を上げて歩き出す。後退は {back#2}、前進はまだ {fwd#2}" \
  --stage 400 "前後に歩けるようになる" "前進 {fwd#2}・後退 {back#2}。横歩きはまだ（{left#2}）/押しへの強さは測定では 3 seed でいちばん強い（全強度の押しで {push#2}。seed 1 は {push#1}）/動画の押しは 1 回だけの例" \
  --stage 1000 "中盤: 前後の速さはほぼ完成" "前進 {fwd#2}・後退 {back#2}。横歩きは {left#2}/押されて転ぶ回数 {push#2}" \
  --stage 2000 "中盤の終わり: 押されても転ばなくなる" "押されて転ぶ回数 {push#2}/学習の押しの強さが最大になる 2080 回目とほぼ同じ時期" \
  --stage 3000 "終盤: 横歩きが伸び、脚を大きく振る" "前進のときの膝の振れ幅: 2000 回目 {knee#2@2000} → 3000 回目 {knee#2}/横歩き {left#2}" \
  --stage 3999 "完成" "前進 {fwd#2}・後退 {back#2}・左へ {left#2}・左旋回 {turn#2}/膝の振れ幅 {knee#2}（3 seed でいちばん大きい）/この方策を 10/13 に実機で 108 秒歩かせた" \
  --outro "seed 2 のまとめ" \
    "100 回目: 3 seed でいちばん早く、その場で回れる" \
    "300〜400 回目: 前後に歩き出す" \
    "押しには最初から 3 seed でいちばん強い（200〜1300 回目に 2〜10 回）" \
    "2000 回目: 押されても転ばなくなる" \
    "3000 回目から: 膝を大きく振る（完成時は 3 seed でいちばん大きい）" \
    "前進はほとんどいつも 3 seed でいちばん遅く（37 時点のうち 34）、胴体の傾きはいちばん大きい" \
  -o media/videos/quad_progress/v31-s2_progress.mp4 2>&1 | grep "^\[record\]\|Error"
}

rec3() {
DISPLAY=:1 OMP_NUM_THREADS=4 python quad/khr_quad_progress.py record -e khr-quadruped31-s3 "${COMMON[@]}" \
  --intro "KHR-3HV 四足歩行 v31 の学習の経過（seed 3）" "全 4000 回の学習のうち 8 つの時点" "${INTRO_BODY[@]}" \
  --stage 0 "学習の前" "$S0" \
  --stage 100 "足を動かし始める" "足を小さく動かすが、まだどの指令にも進めない（左旋回 {turn#3}）/この seed がその場で回れるようになるのは 300 回目（3 seed でいちばん遅い）" \
  --stage 300 "動作が出来始める: その場で回り、後ろへ歩き出す" "その場で回れるようになる（左旋回 {turn#3}）/後退は {back#3} まで歩き出すが、前進はまだ {fwd#3}" \
  --stage 400 "前後に歩けるようになる" "前進 {fwd#3}・後退 {back#3}。横歩きはまだ（{left#3}）/押されて転ぶ回数 {push#3}（seed 1・2 は {push#1}・{push#2}）" \
  --stage 1000 "中盤: 前後の速さはほぼ完成" "前進 {fwd#3}・後退 {back#3}。横歩きは {left#3}（3 seed でいちばん早く伸びる）/押されて転ぶ回数 {push#3}" \
  --stage 2000 "中盤の終わり: 押されても転ばなくなる" "押されて転ぶ回数 {push#3}（1900 回目から 0）/学習の押しの強さが最大になる 2080 回目とほぼ同じ時期" \
  --stage 3000 "終盤: 横歩きが伸びる。脚の振りはまだ変わらない" "横歩きは {left#3}（3 seed でいちばん高い）/膝の振れ幅は {knee#3} のまま（seed 1・2 は {knee#1}・{knee#2} に増えた）" \
  --stage 3999 "完成" "前進 {fwd#3}・後退 {back#3}・左へ {left#3}・左旋回 {turn#3}/膝の振れ幅は 3800 回目から増えて {knee#3}。後脚の足上げ {clear_r#3} は 3 seed でいちばん低い" \
  --outro "seed 3 のまとめ" \
    "300 回目: その場で回れる（3 seed でいちばん遅い）。同じ時期に後ろへ歩き出す" \
    "400 回目: 前後に歩ける。横歩きは 3 seed でいちばん早く伸びる" \
    "押しへの強さは 3 seed の中ほど（200〜1300 回目に 4〜18 回）" \
    "1900 回目: 押されても転ばなくなる" \
    "3800 回目: やっと膝を大きく振り始める（seed 1・2 より 800〜900 回遅い）。後脚の足上げはいつもいちばん低い" \
  -o media/videos/quad_progress/v31-s3_progress.mp4 2>&1 | grep "^\[record\]\|Error"
}

case "$1" in
  1) rec1 ;; 2) rec2 ;; 3) rec3 ;;
  *) rec1 & rec2 & rec3 & wait ;;
esac
